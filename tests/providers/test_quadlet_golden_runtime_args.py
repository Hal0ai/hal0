@pytest.fixture
def comfyui_unit(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> str:
    monkeypatch.setattr(
        "hal0.providers.comfyui.resolve_gpu_device_paths",
        lambda: ["/dev/kfd", "/dev/dri/card1", "/dev/dri/renderD128"],
    )
    monkeypatch.setattr("hal0.providers.comfyui.resolve_gpu_group_ids", lambda: [44, 992])
    monkeypatch.setattr(
        ComfyUIProvider, "_profile_flags", lambda self, slot_cfg: "--use-pytorch-cross-attention"
    )
    monkeypatch.setenv("HAL0_COMFYUI_DATA_ROOT", str(tmp_path))
    # The gate's URLs come from hal0-api's port and bind host: pin the defaults.
    for key in ("HAL0_PORT", "HAL0_BIND_HOST", "HAL0_COMFYUI_GATE_FAIL_OPEN"):
        monkeypatch.delenv(key, raising=False)
    slot_cfg: dict[str, Any] = {
        "name": "img",
        "type": "image",
        "provider": "comfyui",
        "device": "gpu-rocm",
        "runtime": "container",
        "profile": "comfyui",
        "enabled": True,
        "port": 8188,
        "image_pin": "ghcr.io/hal0ai/hal0-runner-comfyui:golden",
        "model": {"default": "sdxl-turbo"},
    }
    spec = ComfyUIProvider().container_spec(slot_cfg, {})
    return _render_quadlet_from_plan("img", spec).replace(str(tmp_path), "<data_root>")


@pytest.fixture
def flm_unit(monkeypatch: pytest.MonkeyPatch) -> str:
    monkeypatch.setattr(
        "hal0.providers.flm._npu_device_nodes",
        lambda: ["/dev/accel/accel0", "/dev/dri/renderD128"],
    )
    monkeypatch.setattr("hal0.providers.flm._resolve_render_gid", lambda: 992)
    monkeypatch.setattr("hal0.providers.flm._ensure_flm_models_dir", lambda path: None)
    slot_cfg: dict[str, Any] = {
        "name": "npu",
        "port": 8088,
        "device": "npu",
        "runtime": "container",
        "profile": "flm",
        "image_pin": "ghcr.io/hal0ai/hal0-runner-flm:golden",
        "_paths": {"flm_models": "/srv/flm-models"},
        "model": {"default": "gemma3:4b"},
    }
    spec = FLMProvider().container_spec(slot_cfg, {"_model_key": "gemma3:4b"})
    return _render_quadlet_from_plan("npu", spec)


def test_comfyui_unit_is_byte_identical(comfyui_unit: str) -> None:
    assert comfyui_unit == _COMFYUI_GOLDEN


def test_flm_unit_is_byte_identical(flm_unit: str) -> None:
    assert flm_unit == _FLM_GOLDEN
